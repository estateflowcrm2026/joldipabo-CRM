// Sample data for the real estate CRM.
// All timestamps are normalized relative to "today" so the dashboard
// always shows live activity regardless of when the demo is opened.
//
// Date helpers are intentionally split by output type so callers can't
// accidentally call `.toISOString()` on a string or `.slice(0, 10)` on a Date:
//   - offsetDate(days, hours)  → Date object (use .toISOString(), .slice())
//   - offsetIso(days, hours)   → ISO timestamp string
//   - offsetDay(days)          → "YYYY-MM-DD" day string
//   - minutesAgo(minutes)      → ISO timestamp string

import { DEFAULT_PERMISSION_MATRIX, ROLE_DEFINITIONS } from './permissions.js';

const today = () => new Date();
const offsetDate = (days, hours = 0) => {
  const d = today();
  d.setDate(d.getDate() + days);
  d.setHours(d.getHours() + hours);
  return d;
};
const offsetIso = (days, hours = 0) => offsetDate(days, hours).toISOString();
const offsetDay = (days) => offsetDate(days).toISOString().slice(0, 10);
const minutesAgo = (m) => {
  const d = today();
  d.setMinutes(d.getMinutes() - m);
  return d.toISOString();
};

